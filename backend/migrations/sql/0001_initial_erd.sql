-- Court Supply initial PostgreSQL schema.
-- Run this file while connected to the futsal_gear_store database in pgAdmin.
-- It is equivalent to Alembic revision 0001_initial_erd. Do not run both
-- against the same empty database; choose either this script or Alembic.

BEGIN;

CREATE TABLE roles (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(32) NOT NULL UNIQUE,
    CONSTRAINT ck_roles_name
        CHECK (role_name IN ('customer', 'manager', 'administrator'))
);

CREATE TABLE users (
    user_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    role_id SMALLINT NOT NULL REFERENCES roles(role_id) ON DELETE RESTRICT,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_users_email_ci ON users (LOWER(email));

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE brands (
    brand_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(category_id) ON DELETE RESTRICT,
    brand_id BIGINT NOT NULL REFERENCES brands(brand_id) ON DELETE RESTRICT,
    name VARCHAR(180) NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    base_price_minor BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'MYR',
    image_url TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_products_base_price_nonnegative CHECK (base_price_minor >= 0),
    CONSTRAINT ck_products_currency_format CHECK (currency ~ '^[A-Z]{3}$')
);
CREATE INDEX ix_products_category_id ON products (category_id);
CREATE INDEX ix_products_brand_id ON products (brand_id);
CREATE INDEX ix_products_active_name ON products (is_active, name);

CREATE TABLE product_variants (
    variant_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    sku VARCHAR(80) NOT NULL UNIQUE,
    size VARCHAR(40) NOT NULL,
    colour VARCHAR(60) NOT NULL,
    price_minor BIGINT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_variant_product_size_colour UNIQUE (product_id, size, colour),
    CONSTRAINT ck_variants_price_nonnegative CHECK (price_minor >= 0)
);
CREATE INDEX ix_product_variants_product_id ON product_variants (product_id);

CREATE TABLE inventory (
    variant_id BIGINT PRIMARY KEY
        REFERENCES product_variants(variant_id) ON DELETE RESTRICT,
    quantity_on_hand INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_quantity_nonnegative CHECK (quantity_on_hand >= 0)
);

CREATE TABLE orders (
    order_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    customer_id UUID NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    status VARCHAR(20) NOT NULL DEFAULT 'placed',
    subtotal_minor BIGINT NOT NULL,
    shipping_minor BIGINT NOT NULL DEFAULT 0,
    tax_minor BIGINT NOT NULL DEFAULT 0,
    total_minor BIGINT NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'MYR',
    delivery_name VARCHAR(160) NOT NULL,
    delivery_address TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_orders_status CHECK (status IN ('placed', 'shipped', 'delivered')),
    CONSTRAINT ck_orders_amounts_nonnegative CHECK (
        subtotal_minor >= 0 AND shipping_minor >= 0 AND tax_minor >= 0 AND total_minor >= 0
    ),
    CONSTRAINT ck_orders_total_matches_components
        CHECK (total_minor = subtotal_minor + shipping_minor + tax_minor),
    CONSTRAINT ck_orders_currency_format CHECK (currency ~ '^[A-Z]{3}$')
);
CREATE INDEX ix_orders_customer_created ON orders (customer_id, created_at);
CREATE INDEX ix_orders_status_created ON orders (status, created_at);

CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    variant_id BIGINT NOT NULL REFERENCES product_variants(variant_id) ON DELETE RESTRICT,
    product_name_snapshot VARCHAR(180) NOT NULL,
    size_snapshot VARCHAR(40) NOT NULL,
    colour_snapshot VARCHAR(60) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price_minor BIGINT NOT NULL,
    line_total_minor BIGINT NOT NULL,
    CONSTRAINT uq_order_item_order_variant UNIQUE (order_id, variant_id),
    CONSTRAINT ck_order_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_order_items_amounts_nonnegative
        CHECK (unit_price_minor >= 0 AND line_total_minor >= 0),
    CONSTRAINT ck_order_items_line_total
        CHECK (line_total_minor = quantity * unit_price_minor)
);
CREATE INDEX ix_order_items_variant_id ON order_items (variant_id);

CREATE TABLE order_status_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id UUID NOT NULL REFERENCES orders(order_id) ON DELETE RESTRICT,
    changed_by_user_id UUID NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    old_status VARCHAR(20),
    new_status VARCHAR(20) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_order_status_history_new_status
        CHECK (new_status IN ('placed', 'shipped', 'delivered')),
    CONSTRAINT ck_order_status_history_old_status
        CHECK (old_status IS NULL OR old_status IN ('placed', 'shipped', 'delivered'))
);
CREATE INDEX ix_order_status_history_order_changed
    ON order_status_history (order_id, changed_at);

CREATE TABLE inventory_movements (
    movement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id BIGINT NOT NULL REFERENCES product_variants(variant_id) ON DELETE RESTRICT,
    changed_by_user_id UUID REFERENCES users(user_id) ON DELETE RESTRICT,
    order_id UUID REFERENCES orders(order_id) ON DELETE RESTRICT,
    quantity_delta INTEGER NOT NULL,
    reason VARCHAR(80) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_movements_nonzero_delta CHECK (quantity_delta <> 0)
);
CREATE INDEX ix_inventory_movements_variant_created
    ON inventory_movements (variant_id, created_at);

INSERT INTO roles (role_name)
VALUES ('customer'), ('manager'), ('administrator');

COMMIT;
